-- Spotify Music Streaming Database, team T0028.
-- Constraints only (PK, FK, UNIQUE, NOT NULL, CHECK). No other indexes: the Phase 3 baseline must be untuned.
-- Re-runnable: drops and recreates the schema "spotify".

DROP SCHEMA IF EXISTS spotify CASCADE;
CREATE SCHEMA spotify;
SET search_path TO spotify;

CREATE TABLE artists (
    artist_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artist_name       VARCHAR(100) NOT NULL,
    country_code      CHAR(2)      NOT NULL,
    primary_genre     VARCHAR(30)  NOT NULL,
    is_verified       BOOLEAN      NOT NULL DEFAULT FALSE,
    monthly_listeners INTEGER      NOT NULL DEFAULT 0,   -- derived, see docs/02
    created_at        TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_artists_name_not_blank  CHECK (length(btrim(artist_name)) > 0),
    CONSTRAINT ck_artists_country_format  CHECK (country_code ~ '^[A-Z]{2}$'),
    CONSTRAINT ck_artists_genre_not_blank CHECK (length(btrim(primary_genre)) > 0),
    CONSTRAINT ck_artists_listeners_nonneg CHECK (monthly_listeners >= 0)
);

CREATE TABLE albums (
    album_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artist_id    INTEGER      NOT NULL,
    album_title  VARCHAR(200) NOT NULL,
    album_type   VARCHAR(11)  NOT NULL,
    release_date DATE         NOT NULL,
    label        VARCHAR(50)  NOT NULL,
    upc          CHAR(12)     NOT NULL,
    CONSTRAINT fk_albums_artist FOREIGN KEY (artist_id)
        REFERENCES artists (artist_id) ON DELETE RESTRICT,
    CONSTRAINT uq_albums_upc UNIQUE (upc),
    CONSTRAINT ck_albums_title_not_blank CHECK (length(btrim(album_title)) > 0),
    CONSTRAINT ck_albums_type CHECK (album_type IN ('ALBUM', 'EP', 'SINGLE', 'COMPILATION')),
    CONSTRAINT ck_albums_upc_format CHECK (upc ~ '^[0-9]{12}$'),
    CONSTRAINT ck_albums_release_date CHECK (release_date >= DATE '1900-01-01')
);

CREATE TABLE tracks (
    track_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    album_id    INTEGER      NOT NULL,
    disc_no     SMALLINT     NOT NULL DEFAULT 1,
    track_no    SMALLINT     NOT NULL,
    title       VARCHAR(200) NOT NULL,
    duration_ms INTEGER      NOT NULL,
    explicit    BOOLEAN      NOT NULL DEFAULT FALSE,
    isrc        CHAR(12)     NOT NULL,
    popularity  SMALLINT     NOT NULL,
    CONSTRAINT fk_tracks_album FOREIGN KEY (album_id)
        REFERENCES albums (album_id) ON DELETE CASCADE,
    -- a position on an album is identified by (disc, track number), not by track_no alone
    CONSTRAINT uq_tracks_position UNIQUE (album_id, disc_no, track_no),
    CONSTRAINT uq_tracks_isrc UNIQUE (isrc),
    CONSTRAINT ck_tracks_title_not_blank CHECK (length(btrim(title)) > 0),
    CONSTRAINT ck_tracks_disc_positive CHECK (disc_no >= 1),
    CONSTRAINT ck_tracks_trackno_positive CHECK (track_no >= 1),
    CONSTRAINT ck_tracks_duration CHECK (duration_ms BETWEEN 1000 AND 3600000),
    CONSTRAINT ck_tracks_isrc_format CHECK (isrc ~ '^[A-Z]{2}[A-Z0-9]{3}[0-9]{7}$'),
    CONSTRAINT ck_tracks_popularity CHECK (popularity BETWEEN 0 AND 100)
);

CREATE TABLE track_artists (
    track_id  INTEGER     NOT NULL,
    artist_id INTEGER     NOT NULL,
    role      VARCHAR(8)  NOT NULL,
    CONSTRAINT pk_track_artists PRIMARY KEY (track_id, artist_id),
    CONSTRAINT fk_track_artists_track FOREIGN KEY (track_id)
        REFERENCES tracks (track_id) ON DELETE CASCADE,
    CONSTRAINT fk_track_artists_artist FOREIGN KEY (artist_id)
        REFERENCES artists (artist_id) ON DELETE RESTRICT,
    CONSTRAINT ck_track_artists_role CHECK (role IN ('PRIMARY', 'FEATURED'))
);

CREATE TABLE users (
    user_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email        VARCHAR(254) NOT NULL,
    display_name VARCHAR(50)  NOT NULL,
    country_code CHAR(2)      NOT NULL,
    birth_date   DATE         NOT NULL,
    subscription VARCHAR(7)   NOT NULL DEFAULT 'FREE',
    created_at   TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_email_format CHECK (email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
    CONSTRAINT ck_users_email_lowercase CHECK (email = lower(email)),
    CONSTRAINT ck_users_display_name_not_blank CHECK (length(btrim(display_name)) > 0),
    CONSTRAINT ck_users_country_format CHECK (country_code ~ '^[A-Z]{2}$'),
    CONSTRAINT ck_users_subscription CHECK (subscription IN ('FREE', 'PREMIUM', 'FAMILY', 'DUO', 'STUDENT')),
    -- born after 1900 and not after the day the account was created
    CONSTRAINT ck_users_birth_date CHECK (
        birth_date >= DATE '1900-01-01'
        AND birth_date <= (created_at AT TIME ZONE 'UTC')::date
    )
);

CREATE TABLE playlists (
    playlist_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id    INTEGER      NOT NULL,
    name             VARCHAR(100) NOT NULL,
    is_public        BOOLEAN      NOT NULL DEFAULT FALSE,
    is_collaborative BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMPTZ  NOT NULL,
    CONSTRAINT fk_playlists_owner FOREIGN KEY (owner_user_id)
        REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT ck_playlists_name_not_blank CHECK (length(btrim(name)) > 0),
    -- Spotify rule: a collaborative playlist cannot be public
    CONSTRAINT ck_playlists_collab_not_public CHECK (NOT (is_public AND is_collaborative))
);

-- Key is (playlist_id, position): the same track can appear twice in a playlist (R22), so (playlist_id, track_id) is not unique.
-- added_by_user_id turns NULL only if that user deletes their account.
CREATE TABLE playlist_tracks (
    playlist_id      INTEGER     NOT NULL,
    position         SMALLINT    NOT NULL,
    track_id         INTEGER     NOT NULL,
    added_by_user_id INTEGER,
    added_at         TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_playlist_tracks PRIMARY KEY (playlist_id, position),
    CONSTRAINT fk_playlist_tracks_playlist FOREIGN KEY (playlist_id)
        REFERENCES playlists (playlist_id) ON DELETE CASCADE,
    CONSTRAINT fk_playlist_tracks_track FOREIGN KEY (track_id)
        REFERENCES tracks (track_id) ON DELETE CASCADE,
    CONSTRAINT fk_playlist_tracks_added_by FOREIGN KEY (added_by_user_id)
        REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT ck_playlist_tracks_position CHECK (position >= 1)
);

-- user_id turns NULL only if the listener deletes their account; the stream stays because royalties are paid on it.
-- playlist_id is NULL for non-playlist sources and after its playlist is deleted.
CREATE TABLE streams (
    stream_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER,
    track_id    INTEGER     NOT NULL,
    started_at  TIMESTAMPTZ NOT NULL,
    ms_played   INTEGER     NOT NULL,
    platform    VARCHAR(7)  NOT NULL,
    source_type VARCHAR(8)  NOT NULL,
    playlist_id INTEGER,
    skipped     BOOLEAN     NOT NULL,
    offline     BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_streams_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT fk_streams_track FOREIGN KEY (track_id)
        REFERENCES tracks (track_id) ON DELETE RESTRICT,
    CONSTRAINT fk_streams_playlist FOREIGN KEY (playlist_id)
        REFERENCES playlists (playlist_id) ON DELETE SET NULL,
    CONSTRAINT ck_streams_ms_played CHECK (ms_played BETWEEN 0 AND 3600000),
    CONSTRAINT ck_streams_platform CHECK (platform IN ('ANDROID', 'IOS', 'WEB', 'DESKTOP', 'CAR', 'SPEAKER')),
    CONSTRAINT ck_streams_source_type CHECK (source_type IN ('PLAYLIST', 'ALBUM', 'ARTIST', 'RADIO', 'SEARCH')),
    -- only a PLAYLIST stream may carry a playlist_id. The reverse is not enforced:
    -- ON DELETE SET NULL would break it when a played playlist is deleted.
    CONSTRAINT ck_streams_playlist_only_for_playlist CHECK (source_type = 'PLAYLIST' OR playlist_id IS NULL),
    -- skipped is stored, but must agree with the 30-second rule on ms_played
    CONSTRAINT ck_streams_skipped_rule CHECK (skipped = (ms_played < 30000))
);

CREATE TABLE liked_tracks (
    user_id  INTEGER     NOT NULL,
    track_id INTEGER     NOT NULL,
    liked_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_liked_tracks PRIMARY KEY (user_id, track_id),
    CONSTRAINT fk_liked_tracks_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_liked_tracks_track FOREIGN KEY (track_id)
        REFERENCES tracks (track_id) ON DELETE CASCADE
);

CREATE TABLE artist_follows (
    user_id     INTEGER     NOT NULL,
    artist_id   INTEGER     NOT NULL,
    followed_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_artist_follows PRIMARY KEY (user_id, artist_id),
    CONSTRAINT fk_artist_follows_user FOREIGN KEY (user_id)
        REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_artist_follows_artist FOREIGN KEY (artist_id)
        REFERENCES artists (artist_id) ON DELETE CASCADE
);
